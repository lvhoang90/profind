// Thử inCoverage (scripts/lib/coverage.mjs): node test/coverage.test.mjs
import { inCoverage } from "../scripts/lib/coverage.mjs";
let ok = 0; const eq = (a, b, m) => { if (a !== b) { console.error("FAIL", m, a, b); process.exit(1); } ok++; };
eq(inCoverage("2015", 2015), true, "một năm: đúng");
eq(inCoverage("2015", 2014), false, "một năm: trước");
eq(inCoverage("2015", 2016), false, "một năm: sau");
eq(inCoverage("2010-2020", 2015), true, "khoảng: giữa");
eq(inCoverage("2010-2020", 2010), true, "khoảng: biên đầu");
eq(inCoverage("2010-2020", 2020), true, "khoảng: biên cuối");
eq(inCoverage("2010-2020", 2009), false, "khoảng: ngay trước");
eq(inCoverage("2010-2020", 2021), false, "khoảng: ngay sau");
eq(inCoverage("1996-2005,2010-2026", 2007), false, "khoảng hở: 2007");
eq(inCoverage("1996-2005,2010-2026", 2012), true, "khoảng hở: 2012");
eq(inCoverage("1996-2005,2010-2026", 2005), true, "khoảng hở: biên cuối đoạn 1");
eq(inCoverage("1996-2005,2010-2026", 2010), true, "khoảng hở: biên đầu đoạn 2");
eq(inCoverage("1996-2005,2010-2026", 2026), true, "khoảng hở: biên cuối đoạn 2");
eq(inCoverage("1996-2005,2010-2026", 1995), false, "khoảng hở: trước đoạn 1");
eq(inCoverage("1996-2005;2010-2026", 2007), false, "chấm phẩy: 2007");
eq(inCoverage("1996-2005;2010-2026", 2012), true, "chấm phẩy: 2012");
eq(inCoverage("1990;1995-1996;2001", 2001), true, "ba đoạn lẫn năm đơn: 2001");
eq(inCoverage("1990;1995-1996;2001", 1990), true, "ba đoạn: 1990");
eq(inCoverage("1990;1995-1996;2001", 1993), false, "ba đoạn: 1993");
eq(inCoverage("1990,1995;2001", 1995), true, "trộn , và ;");
eq(inCoverage("", 2015), false, "rỗng");
eq(inCoverage(null, 2015), false, "null");
eq(inCoverage(undefined, 2015), false, "undefined cov");
eq(inCoverage("2010-2020", 0), false, "năm 0");
eq(inCoverage("2010-2020", undefined), false, "năm undefined");
eq(inCoverage("2010-2020", null), false, "năm null");
eq(inCoverage("abc", 2015), false, "chuỗi rác");
eq(inCoverage("2010-20", 2015), false, "đoạn sai định dạng");
eq(inCoverage("2010-2020", "2015") , true, "năm dạng chuỗi số (so sánh số hóa)");
console.log(`OK ${ok} kiểm tra`);
